// Copies the web app (../web) into www/ for Capacitor and points it at your hosted API.
//
//   VOCALIZE_API_BASE=https://api.example.com npm run sync
//
// The native app loads its UI from the device, so every API call must go to a real,
// HTTPS-hosted Vocalize server (see ../DEPLOYMENT.md).
import { cpSync, existsSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', 'web');
const out = join(here, '..', 'www');

const apiBase = (process.env.VOCALIZE_API_BASE || '').replace(/\/$/, '');
if (!/^https:\/\//.test(apiBase)) {
  console.error('Set VOCALIZE_API_BASE to your server\'s https:// address, e.g.\n  VOCALIZE_API_BASE=https://api.example.com npm run sync');
  process.exit(1);
}

if (existsSync(out)) rmSync(out, { recursive: true });
cpSync(src, out, {
  recursive: true,
  // The service worker and share page are for the website only.
  filter: (p) => !/[\\/](sw\.js|share\.html)$/.test(p),
});
writeFileSync(join(out, 'js', 'config.js'),
  `// Generated by mobile/scripts/sync-web.mjs. Do not edit; change VOCALIZE_API_BASE and re-sync.\n` +
  `window.VOCALIZE_CONFIG = ${JSON.stringify({ apiBase }, null, 2)};\n`);
console.log(`Copied web app to www/ (API: ${apiBase})`);
